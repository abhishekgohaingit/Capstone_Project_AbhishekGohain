from pathlib import Path

import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter

# Use the current folder as the project root.
# Change this only if your data folder is somewhere else.
ROOT = Path.cwd()
DATA_DIR = ROOT / "data"
OUTPUT_DIR = ROOT / "visualizations"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

# Load raw CSV files
customers = pd.read_csv(DATA_DIR / "customers.csv")
products = pd.read_csv(DATA_DIR / "products.csv")
orders = pd.read_csv(DATA_DIR / "orders.csv")

print("Raw orders shape:", orders.shape)
print("Products shape:", products.shape)
print("Customers shape:", customers.shape)

# Task 2: standardize payment method values
orders["payment_method"] = (
    orders["payment_method"]
    .str.strip()
    .str.upper()
)

# Task 3: remove duplicate orders, ignoring order_id
natural_key = [
    "customer_id",
    "product_id",
    "order_date",
    "quantity",
    "discount_pct",
    "payment_method",
    "rating",
    "returned",
]
duplicate_mask = orders.duplicated(subset=natural_key, keep="first")
orders_clean = orders.loc[~duplicate_mask].copy()

print("Duplicate orders removed:", int(duplicate_mask.sum()))
print("Cleaned orders shape:", orders_clean.shape)

# Task 4: impute missing values
orders_clean["discount_pct"] = orders_clean["discount_pct"].fillna(0)
rating_median = orders_clean["rating"].median()
orders_clean["rating"] = orders_clean["rating"].fillna(rating_median)

# Task 5: merge orders with products and customers
merged = (
    orders_clean
    .merge(products, on="product_id", how="left", validate="many_to_one")
    .merge(customers, on="customer_id", how="left", validate="many_to_one")
)

# Calculate order value using the same formula as clean_and_eda.py
merged["order_value"] = (
    merged["quantity"]
    * merged["price"]
    * (1 - merged["discount_pct"] / 100)
)

# Task 6: flag quantity outliers using the same IQR rule
q1 = merged["quantity"].quantile(0.25)
q3 = merged["quantity"].quantile(0.75)
iqr = q3 - q1
lower = q1 - 1.5 * iqr
upper = q3 + 1.5 * iqr

merged["is_outlier"] = (
    (merged["quantity"] < lower)
    | (merged["quantity"] > upper)
)

merged["order_date"] = pd.to_datetime(merged["order_date"])

print(f"Quantity IQR limits: {lower:.1f} to {upper:.1f}")
print("Quantity outlier orders:")
display(merged.loc[merged["is_outlier"], ["order_id", "quantity"]])

"""## 2. Chart 1 — Return rate by cleaned payment method"""

# Calculate return rate for each cleaned payment method
return_by_payment = (
    merged.groupby("payment_method")["returned"]
    .agg(["count", "mean"])
)

return_by_payment["return_rate_pct"] = return_by_payment["mean"] * 100
return_by_payment = return_by_payment.sort_values(
    "return_rate_pct",
    ascending=False
)

print("Return rates by payment method (%):")
display(return_by_payment[["count", "return_rate_pct"]].round(1))

# Find the highest return-rate method and compare it with CARD
highest_method = return_by_payment.index[0]
highest_rate = return_by_payment.iloc[0]["return_rate_pct"]
card_rate = return_by_payment.loc["CARD", "return_rate_pct"]
ratio = highest_rate / card_rate if card_rate else 0

fig, ax = plt.subplots(figsize=(8, 5))

bars = ax.bar(
    return_by_payment.index,
    return_by_payment["return_rate_pct"],
    width=0.65
)

# Exact percentage labels, formatted to one decimal place
ax.bar_label(
    bars,
    labels=[f"{rate:.1f}%" for rate in return_by_payment["return_rate_pct"]],
    padding=4
)

ax.set_title(
    f"{highest_method} Returns at {highest_rate:.1f}% — {ratio:.0f}x Card",
    fontsize=13,
    fontweight="bold",
    pad=14
)
ax.set_xlabel("Payment Method")
ax.set_ylabel("Return Rate (%)")
ax.set_ylim(0, highest_rate * 1.18)
ax.spines["top"].set_visible(False)
ax.spines["right"].set_visible(False)

plt.tight_layout()

chart1_path = OUTPUT_DIR / "return_rate_by_payment.png"
plt.savefig(chart1_path, dpi=150, bbox_inches="tight")
plt.show()
plt.close()

print("Saved:", chart1_path)

"""## 3. Chart 2 — Outlier-corrected monthly revenue"""

# Exclude only the quantity outliers flagged by the Task 6 IQR rule
corrected_orders = merged.loc[~merged["is_outlier"]].copy()
corrected_orders["year_month"] = corrected_orders["order_date"].dt.to_period("M")

# This is the outlier-corrected series from Task 10
monthly_revenue = (
    corrected_orders.groupby("year_month")["order_value"]
    .sum()
    .sort_index()
)

print("Outlier-corrected monthly revenue:")
display(monthly_revenue.round(2).rename("order_value").to_frame())

# Find the true peak month after excluding quantity outliers
peak_month = monthly_revenue.idxmax()
peak_revenue = monthly_revenue.max()
peak_month_name = peak_month.strftime("%B %Y")

print(f"Actual peak month: {peak_month_name} ({peak_revenue:.2f})")

fig, ax = plt.subplots(figsize=(9, 5))

ax.plot(
    monthly_revenue.index.astype(str),
    monthly_revenue.values,
    marker="o",
    markersize=7,
    linewidth=2
)

ax.set_title(
    f"Outlier-Corrected Monthly Revenue — Peak: {peak_month_name}",
    fontsize=13,
    fontweight="bold",
    pad=14
)
ax.set_xlabel("Month")
ax.set_ylabel("Revenue")
ax.yaxis.set_major_formatter(
    FuncFormatter(lambda value, _: f"{value:,.0f}")
)

ax.spines["top"].set_visible(False)
ax.spines["right"].set_visible(False)
plt.xticks(rotation=45)
plt.tight_layout()

chart2_path = OUTPUT_DIR / "monthly_revenue_trend.png"
plt.savefig(chart2_path, dpi=150, bbox_inches="tight")
plt.show()
plt.close()

print("Saved:", chart2_path)

