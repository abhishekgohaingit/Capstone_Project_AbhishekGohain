"""## 6. Online SCR narrative with fallback — Tasks 2 and 3

The request uses `temperature=0.0`, an explicit token limit, a 15-second timeout, and exception handling. Missing keys or API errors route to the offline function.
"""

def _generate_scr_narrative_online(findings: dict, api_key: str) -> dict:
    """Call Gemini once and always return a structured success/error dictionary."""
    try:
        client = genai.Client(api_key=api_key)
        system_instruction = """
You are a senior data analyst writing for Mamaearth's regional ops and finance heads.
Write exactly three labeled sections: Situation, Complication, and Resolution.
Use only the supplied findings. Do not invent, estimate, calculate, or change statistics.
Preserve numeric values from the findings. For the peak month 2026-03, write
"March (2026-03)" and include its revenue value. Use a clear, professional tone.
"""
        contents = f"""Write an SCR business analysis report based only on these findings.
Include all five required figures: cleaned total revenue, COD return rate,
COD + Tier-2 return rate, duplicate-driven reconciliation delta, and true peak
month with revenue. Do not pre-format or change the numeric values.

FINDINGS:
{json.dumps(findings, indent=2, ensure_ascii=False)}
"""
        response = client.models.generate_content(
            model="gemini-3.5-flash-lite",
            contents=contents,
            config=types.GenerateContentConfig(
                system_instruction=system_instruction,
                # Temperature 0.0 suits a factual business report: consistency
                # and numeric accuracy matter more than creative variation.
                temperature=0.0,
                max_output_tokens=500,
                http_options=types.HttpOptions(timeout=15000),
            ),
        )
        narrative = (response.text or "").strip()
        if not narrative:
            raise ValueError(
                "Gemini returned no text. Check that the selected model supports text generation."
            )

        return {
            "status": "success",
            "mode": "online",
            "narrative": narrative,
            "tokens": (
                response.usage_metadata.total_token_count
                if getattr(response, "usage_metadata", None) else None
            ),
        }
    except Exception as err:
        # Structured error branch: never pass a raw exception to the caller.
        return {"status": "error", "narrative": None, "message": str(err)}


def generate_scr_narrative(findings: dict) -> dict:
    """Generate an SCR narrative, falling back offline if Gemini is missing or fails."""
    api_key = _get_api_key()

    # Task 4: no key or no Gemini library means no network call at all.
    if not api_key or genai is None or types is None:
        return generate_scr_narrative_offline(findings)

    online_result = _generate_scr_narrative_online(findings, api_key)

    # Task 4: an API error triggers the deterministic offline fallback.
    if online_result.get("status") == "error":
        offline_result = generate_scr_narrative_offline(findings)
        if offline_result.get("status") == "success":
            return offline_result
        # Both paths failed: still return a structured error dictionary.
        return {
            "status": "error",
            "narrative": None,
            "message": (
                f"Gemini error: {online_result.get('message', 'Unknown error')}; "
                f"offline error: {offline_result.get('message', 'Unknown error')}"
            ),
        }

    return online_result

"""## 7. Numeric accuracy checker — Task 5

The checker prints PASS/FAIL for each required figure, verifies March and its peak revenue together, and asserts if any check fails.
"""

def check_narrative_numbers(narrative: str, *, raise_on_failure: bool = True) -> bool:
    """Print PASS/FAIL for all five required figures; normalize comma separators."""
    normalised = narrative.lower().replace(",", "").replace("$", "").replace("₹", "")
    checks = [
        ("Cleaned total revenue: 97,358.30", ("97358.3", "97358.30")),
        ("COD return rate: 44.4", ("44.4",)),
        ("COD + Tier-2 return rate: 54.5", ("54.5",)),
        ("Reconciliation delta: 2,501.90", ("2501.9", "2501.90")),
    ]

    all_passed = True
    for label, acceptable in checks:
        passed = any(value in normalised for value in acceptable)
        print(f"{'PASS' if passed else 'FAIL'} — {label}")
        all_passed = all_passed and passed

    # Task 5 explicitly asks for March together with the peak revenue.
    peak_month_present = "march" in normalised
    peak_revenue_present = "20318.9" in normalised or "20318.90" in normalised
    peak_passed = peak_month_present and peak_revenue_present
    print(f"{'PASS' if peak_passed else 'FAIL'} — March with 20,318.90 peak revenue")

    passed_all = all_passed and peak_passed
    if not passed_all and raise_on_failure:
        raise AssertionError(
            "Numeric accuracy checklist failed. The caller may use the offline fallback."
        )
    return passed_all

"""## 8. Load findings, run, and save the output

This function loads `narrator/findings.json` (or `findings.json`), prints the narrative, saves it to `narrator/sample_output.txt`, and runs the numeric checker.
"""

def main() -> None:
    """Load findings, generate a narrative, save it, and verify all required figures."""
    findings_path = Path("narrator/findings.json")
    if not findings_path.exists():
        findings_path = Path("findings.json")
    if not findings_path.exists():
        print("Could not find narrator/findings.json or findings.json. Provide the findings file and retry.")
        return

    try:
        with findings_path.open("r", encoding="utf-8") as file:
            findings = json.load(file)
    except Exception as err:
        print(f"Could not read findings file: {err}")
        return

    result = generate_scr_narrative(findings)
    if result.get("status") != "success" or not result.get("narrative"):
        print("Narrative generation failed:", result.get("message", "Unknown error"))
        # Try offline one more time, so a transient online failure doesn't stop the notebook.
        result = generate_scr_narrative_offline(findings)

    if result.get("status") != "success" or not result.get("narrative"):
        print("Offline narrative generation failed:", result.get("message", "Unknown error"))
        return

    narrative = result["narrative"]
    print("Status:", result["status"])
    print("Generation mode:", result.get("mode", "unknown"))
    print(narrative)
    if result.get("tokens") is not None:
        print("Tokens used:", result["tokens"])

    # If the online narrative omits a required figure, replace it with the
    # deterministic offline narrative before saving. This prevents a final-cell
    # assertion error and guarantees that the saved sample passes the checklist.
    if not check_narrative_numbers(narrative, raise_on_failure=False):
        print("\nOnline narrative did not pass every numeric check; using the offline template.")
        fallback = generate_scr_narrative_offline(findings)
        if fallback.get("status") != "success" or not fallback.get("narrative"):
            print("Offline fallback failed:", fallback.get("message", "Unknown error"))
            return
        narrative = fallback["narrative"]
        result = fallback
        print("\nGeneration mode: OFFLINE (numeric validation fallback)")
        print("\nOffline fallback narrative:")
        print(narrative)
        print("\nOffline numeric checklist:")

    # Offline is deterministic and must pass; raise only if source findings are invalid.
    check_narrative_numbers(narrative, raise_on_failure=True)

    output_path = Path("narrator/sample_output.txt")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(narrative + "\n", encoding="utf-8")
    print("Saved verified narrative to:", output_path)

"""## 9. Run the generator

We run this final cell after running all preceding cells. It reads `narrator/findings.json` (or `findings.json`), tries Gemini if configured, falls back to the deterministic offline template when needed, validates all five required figures, and saves the verified narrative to `narrator/sample_output.txt`. The final cell should not fail merely because Gemini omits a figure; the offline template is used instead.
"""

main()

